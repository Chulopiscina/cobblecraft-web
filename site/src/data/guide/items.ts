// Keep every book's actual compatibility/effect in the same audited table as its guide.
for(const family of enchantFamilies) {
  const id=`progression:enchant/${family.id}_1`;
  let item=items.find(i=>i.realId===id);
  if(!item) {
    const slug=family.itemSlug??`libro-${family.id.replaceAll("_","-")}`;
    item={slug,realId:id,name:`Libro: ${family.name}`,category:"encantamientos",rarity:"Común",image:null,
      description:family.effect,obtainedFrom:"Tier I al Encantador. Combina dos libros iguales del mismo nivel para avanzar hasta VI.",usedFor:family.appliesTo??"",tradable:true,craftable:false,relatedGuideSection:"/guia/encantamientos"};
    items.push(item);
  }
  item.description=family.effect;
  item.usedFor=`Compatible: ${family.appliesTo}. Valores I–VI: ${family.tiers?.join(" · ")}.`;
}

export function getItem(slug: string): GuideItem | undefined {
  return items.find((i) => i.slug === slug);
}

export function itemsByCategory(category: string): GuideItem[] {
  return items.filter((i) => i.category === category);
}

